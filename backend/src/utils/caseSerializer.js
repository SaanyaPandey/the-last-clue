/**
 * THE LAST CLUE — Procedurally Generated Mystery Investigation Game
 * Case Serializer Utility
 *
 * Responsibilities:
 * 1. Convert Graph instance into JSON-safe { nodes, edges } structure.
 * 2. Sanitize and strip hidden solution attributes (e.g. isMurderWeapon).
 * 3. Enforce strict public field whitelisting for player-facing API responses.
 * 4. Guarantee no hidden solution fields (culprit, motive, weapon, location) leak.
 */

/**
 * Serializes a Graph instance into JSON-safe node and edge arrays.
 * Strips internal Map representations and hidden solution metadata.
 *
 * @param {import('../algorithms/Graph')} graph - Graph data structure instance.
 * @returns {{ nodes: Array<Object>, edges: Array<Object> }} Serialized graph object.
 */
function serializeGraph(graph) {
  if (!graph || typeof graph.getNodes !== 'function' || typeof graph.getEdges !== 'function') {
    return { nodes: [], edges: [] };
  }

  const nodes = graph.getNodes().map(node => {
    const safeMetadata = { ...(node.metadata || {}) };
    // Strip hidden solution indicators from metadata if present
    delete safeMetadata.isMurderWeapon;

    return {
      id: node.id,
      type: node.type,
      label: node.label,
      metadata: safeMetadata
    };
  });

  const edges = graph.getEdges().map(edge => ({
    source: edge.from,
    target: edge.to,
    relationship: edge.type,
    metadata: edge.metadata ? { ...edge.metadata } : {}
  }));

  return {
    nodes,
    edges
  };
}

/**
 * Whitelists safe public fields from raw case data object.
 * Deliberately excludes solution, culprit, motive, murder weapon, and red herring solution tags.
 *
 * @param {Object} caseData - Full case data object generated by MysteryGenerator.
 * @returns {Object} Public API-safe case payload.
 */
function serializePublicCase(caseData, options = {}) {
  if (!caseData) return null;

  const result = {
    caseId: caseData.caseId,
    seed: caseData.seed,
    difficulty: caseData.difficulty,
    suspects: caseData.suspects || [],
    locations: caseData.locations || [],
    weapons: caseData.weapons || [],
    motives: caseData.motives || [],
    clues: caseData.clues || [],
    startingClueId: caseData.startingClueId,
    graph: serializeGraph(caseData.graph),
    metadata: {
      clueCount: caseData.metadata?.clueCount ?? (caseData.clues ? caseData.clues.length : 0),
      redHerringCount: caseData.metadata?.redHerringCount ?? 0,
      suspectCount: caseData.metadata?.suspectCount ?? (caseData.suspects ? caseData.suspects.length : 0),
      isUniqueSolution: caseData.metadata?.isUniqueSolution ?? true,
      generatorVersion: caseData.metadata?.generatorVersion || '1.0.0'
    }
  };

  const instanceId = options.caseInstanceId || caseData.caseInstanceId;
  if (instanceId) {
    result.caseInstanceId = instanceId;
  }

  return result;
}

module.exports = {
  serializeGraph,
  serializePublicCase
};
